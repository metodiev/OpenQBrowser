void LayoutTest::growsDocumentHeightWithContent()
{
    Page shortPage(QStringLiteral("<body><p>one</p></body>"));
    Page longPage(QStringLiteral(
        "<body><div style=\"height: 3000px\">tall</div></body>"));

    QVERIFY(longPage.result.documentHeight > shortPage.result.documentHeight);
    QVERIFY(longPage.result.documentHeight >= 3000.0);
    // A page shorter than the viewport still reports the viewport height, so
    // the window background fills correctly.
    QVERIFY(shortPage.result.documentHeight >= 600.0);
}

void LayoutTest::paintsBackgroundColours()
{
    Page page(QStringLiteral(
        "<body><style>body { margin: 0; background: #f5f5f5 } "
        "#a { width: 100px; height: 50px; background: #ff0000 }</style>"
        "<div id=\"a\"></div></body>"));

    const QImage image = renderer::Painter::renderToImage(page.boxTree.get(), 800, 600);
    QVERIFY(!image.isNull());

    renderer::Box *box = page.boxForId(QStringLiteral("a"));
    const int centerX = static_cast<int>(box->x() + box->width() / 2);
    const int centerY = static_cast<int>(box->y() + box->height() / 2);

    QCOMPARE(image.pixelColor(centerX, centerY), QColor(255, 0, 0));
    // Outside the box the body background shows through.
    QCOMPARE(image.pixelColor(500, 300), QColor(245, 245, 245));
}

void LayoutTest::paintsTextPixels()
{
    Page page(QStringLiteral(
        "<body><style>body { margin: 0; background: white; color: black; font-size: 40px }"
        "</style><div>MMMM</div></body>"));

    const QImage image = renderer::Painter::renderToImage(page.boxTree.get(), 400, 200);

    // Large black text on white must produce dark pixels.
    int dark = 0;
    for (int y = 0; y < image.height(); ++y) {
        for (int x = 0; x < image.width(); ++x) {
            if (image.pixelColor(x, y).lightness() < 100)
                ++dark;
        }
    }
    QVERIFY2(dark > 200, qPrintable(QStringLiteral("only %1 dark pixels").arg(dark)));
}

void LayoutTest::cullsOffscreenContent()
{
    // A box far below the viewport must not be painted.
    Page page(QStringLiteral(
        "<body><style>body { margin: 0 } #far { margin-top: 5000px; height: 50px; "
        "background: #00ff00 }</style><div id=\"far\"></div></body>"));

    renderer::Box *box = page.boxForId(QStringLiteral("far"));
    QVERIFY(box != nullptr);
    // A 5000px top margin places the box's border edge exactly 5000px down.
    QCOMPARE(box->y(), 5000.0);
    // The document is tall enough to scroll to it.
    QVERIFY(page.result.documentHeight >= 5050.0);

    const QImage image = renderer::Painter::renderToImage(page.boxTree.get(), 400, 300);

    // No green anywhere in the visible area.
    int green = 0;
    for (int y = 0; y < image.height(); ++y) {
        for (int x = 0; x < image.width(); ++x) {
            const QColor c = image.pixelColor(x, y);
            if (c.green() > 200 && c.red() < 100 && c.blue() < 100)
                ++green;
        }
    }
    QCOMPARE(green, 0);
}

