void LayoutTest::buildsBoxesForElements()
{
    Page page(QStringLiteral("<body><div id=\"a\">x</div></body>"));

    QVERIFY(page.boxTree != nullptr);
    renderer::Box *box = page.boxForId(QStringLiteral("a"));
    QVERIFY(box != nullptr);
    QCOMPARE(box->type(), renderer::Box::Type::Block);
    QVERIFY(box->width() > 0);
}

void LayoutTest::skipsDisplayNone()
{
    Page page(QStringLiteral(
        "<body><style>.gone { display: none }</style>"
        "<div id=\"a\">shown</div><div id=\"b\" class=\"gone\">hidden</div></body>"));

    QVERIFY(page.boxForId(QStringLiteral("a")) != nullptr);
    QVERIFY(page.boxForId(QStringLiteral("b")) == nullptr);
}

void LayoutTest::createsAnonymousBlocks()
{
    // Inline content between blocks is wrapped so a block container never mixes
    // block and inline children directly.
    Page page(QStringLiteral("<body><div id=\"a\">text<p>block</p>more</div></body>"));

    renderer::Box *box = page.boxForId(QStringLiteral("a"));
    QVERIFY(box != nullptr);
    QVERIFY(box->childCount() >= 2);

    bool sawAnonymous = false;
    for (const auto &child : box->children()) {
        if (child->type() == renderer::Box::Type::Anonymous)
            sawAnonymous = true;
    }
    QVERIFY(sawAnonymous);
}

void LayoutTest::laysOutBlockStack()
{
    Page page(QStringLiteral(
        "<body><div id=\"a\">one</div><div id=\"b\">two</div><div id=\"c\">three</div></body>"));

    renderer::Box *a = page.boxForId(QStringLiteral("a"));
    renderer::Box *b = page.boxForId(QStringLiteral("b"));
    renderer::Box *c = page.boxForId(QStringLiteral("c"));

    QVERIFY(a && b && c);
    // Blocks stack: each starts below the previous one.
    QVERIFY(b->y() >= a->y() + a->height());
    QVERIFY(c->y() >= b->y() + b->height());
    // None overflows the viewport width.
    QVERIFY(a->width() <= 800);
    QCOMPARE(a->width(), 800 - 16); // body has an 8px margin on each side
}

void LayoutTest::appliesPaddingAndBorder()
{
    Page page(QStringLiteral(
        "<body><style>#a { padding: 10px 20px; border: 3px solid black; width: 100px }</style>"
        "<div id=\"a\">x</div></body>"));

    renderer::Box *box = page.boxForId(QStringLiteral("a"));
    QVERIFY(box != nullptr);

    // The border box is the content plus padding plus border on both axes.
    QCOMPARE(box->width(), 100.0 + 40.0 + 6.0);
    QVERIFY(box->height() >= 30.0);
    QCOMPARE(box->contentBox().width(), 100.0);
}

